/** Built-in translations, keyed by primary language subtag. */
export const AKARI_MESSAGES: Readonly<Record<string, AkariMessages>> = {
  zh,
  en,
  ja,
  ko,
  fr,
  ar,
};

export const DEFAULT_MESSAGES_LANG = "en";

/**
 * Picks the built-in translation for a BCP 47 language tag: the full tag
 * first (`zh-cn`), then its primary subtag (`zh`), then English.
 */
export function resolveMessagesLang(lang: string | undefined): string {
  const tag = lang?.trim().toLowerCase() ?? "";
  if (tag in AKARI_MESSAGES) return tag;

  const primary = tag.split(/[-_]/)[0] ?? "";
  return primary in AKARI_MESSAGES ? primary : DEFAULT_MESSAGES_LANG;
}

export function resolveMessages(
  lang: string | undefined,
  overrides: Partial<AkariMessages> = {},
): AkariMessages {
  const messages = { ...AKARI_MESSAGES[resolveMessagesLang(lang)]! };

  for (const key of Object.keys(messages) as Array<keyof AkariMessages>) {
    const value = overrides[key];
    if (typeof value === "string") messages[key] = value;
  }

  return messages;
}

/** Fills `{name}` placeholders; unknown names are left as written. */
export function formatMessage(
  template: string,
  params: Readonly<Record<string, string | number>> = {},
): string {
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in params ? String(params[name]) : match,
  );
}

/** CLDR plural category of `count`, e.g. to tell "1 result" from "2 results". */
export function pluralCategory(
  lang: string,
  count: number,
): Intl.LDMLPluralRule {
  try {
    return new Intl.PluralRules(lang).select(count);
  } catch {
    // Not a valid language tag.
    return count === 1 ? "one" : "other";
  }
}

/**
 * Splits a template around one placeholder, for markup that has to sit in
 * the middle of a translated sentence.
 */
export function splitMessage(
  template: string,
  name: string,
): [before: string, after: string] {
  const token = `{${name}}`;
  const index = template.indexOf(token);
  if (index < 0) return [template, ""];
  return [template.slice(0, index), template.slice(index + token.length)];
}
